GRID_SIZE = 7
IMG_SIZE = 224
NUM_CLASSES = 4

def parse_example(example_proto):
    feature_description = {
        "image/encoded": tf.io.FixedLenFeature([], tf.string),
        "image/object/bbox/xmin": tf.io.VarLenFeature(tf.float32),
        "image/object/bbox/xmax": tf.io.VarLenFeature(tf.float32),
        "image/object/bbox/ymin": tf.io.VarLenFeature(tf.float32),
        "image/object/bbox/ymax": tf.io.VarLenFeature(tf.float32),
        "image/object/class/label": tf.io.VarLenFeature(tf.int64),
    }

    parsed = tf.io.parse_single_example(example_proto, feature_description)

    image = tf.image.decode_jpeg(parsed["image/encoded"], channels=3)
    image = tf.image.resize(image, (IMG_SIZE, IMG_SIZE)) / 255.0

    xmin = tf.sparse.to_dense(parsed["image/object/bbox/xmin"])
    xmax = tf.sparse.to_dense(parsed["image/object/bbox/xmax"])
    ymin = tf.sparse.to_dense(parsed["image/object/bbox/ymin"])
    ymax = tf.sparse.to_dense(parsed["image/object/bbox/ymax"])
    labels = tf.sparse.to_dense(parsed["image/object/class/label"])

    target = tf.zeros((GRID_SIZE, GRID_SIZE, 5 + NUM_CLASSES), dtype=tf.float32)

    def loop_body(i, target):
        x_center = (xmin[i] + xmax[i]) / 2.0
        y_center = (ymin[i] + ymax[i]) / 2.0
        w = xmax[i] - xmin[i]
        h = ymax[i] - ymin[i]

        grid_x = tf.cast(x_center * GRID_SIZE, tf.int32)
        grid_y = tf.cast(y_center * GRID_SIZE, tf.int32)

        grid_x = tf.clip_by_value(grid_x, 0, GRID_SIZE - 1)
        grid_y = tf.clip_by_value(grid_y, 0, GRID_SIZE - 1)

        class_vec = tf.one_hot(labels[i], NUM_CLASSES)

        update = tf.concat([
            [x_center, y_center, w, h, 1.0],
            class_vec
        ], axis=0)

        target = tf.tensor_scatter_nd_update(
            target,
            indices=[[grid_y, grid_x]],
            updates=[update]
        )

        return i + 1, target

    i = tf.constant(0)
    n = tf.shape(labels)[0]

    _, target = tf.while_loop(
        lambda i, target: i < n,
        loop_body,
        [i, target]
    )

    return image, target


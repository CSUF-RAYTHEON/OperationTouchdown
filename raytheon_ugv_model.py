def iou(box1, box2):
    x1 = max(box1[0], box2[0])
    y1 = max(box1[1], box2[1])
    x2 = min(box1[2], box2[2])
    y2 = min(box1[3], box2[3])

    inter = max(0, x2 - x1) * max(0, y2 - y1)

    area1 = (box1[2]-box1[0]) * (box1[3]-box1[1])
    area2 = (box2[2]-box2[0]) * (box2[3]-box2[1])

    union = area1 + area2 - inter
    return inter / (union + 1e-6)

def decode_predictions(pred, conf_thresh=0.3):
    boxes = []

    for y in range(GRID_SIZE):
        for x in range(GRID_SIZE):
            cell = pred[y, x]

            bx, by, bw, bh = cell[0:4]
            obj = 1 / (1 + np.exp(-np.clip(cell[4], -10, 10)))
            cls = cell[5:]
            cls = np.exp(cls) / np.sum(np.exp(cls))

            score = obj * np.max(cls)
            class_id = np.argmax(cls)

            if score > conf_thresh:
                cx = (x + bx) / GRID_SIZE
                cy = (y + by) / GRID_SIZE

                xmin = cx - bw / 2
                ymin = cy - bh / 2
                xmax = cx + bw / 2
                ymax = cy + bh / 2

                boxes.append([xmin, ymin, xmax, ymax, score, class_id])

    boxes = sorted(boxes, key=lambda x: x[4], reverse=True)

    filtered = []
    for box in boxes:
        keep = True
        for f in filtered:
            if iou(box, f) > 0.4:
                keep = False
                break
        if keep:
            filtered.append(box)

    return filtered


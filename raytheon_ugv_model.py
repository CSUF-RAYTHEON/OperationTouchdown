def show_prediction(image, pred):
    boxes = decode_predictions(pred)

    h, w, _ = image.shape
    plt.imshow(image)

    for box in boxes:
        xmin, ymin, xmax, ymax, score, cls = box

        xmin *= w
        xmax *= w
        ymin *= h
        ymax *= h

        plt.gca().add_patch(
            plt.Rectangle(
                (xmin, ymin),
                xmax - xmin,
                ymax - ymin,
                fill=False,
                color="red",
                linewidth=2
            )
        )

        plt.text(xmin, ymin, f"{CLASS_NAMES[int(cls)]}:{score:.2f}", color="red")

    plt.show()

